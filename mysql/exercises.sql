-- J1  [בינוני]  אילו מחוזות מופיעים גם בהזמנה שסופקה וגם בהזמנה שלא סופקה? השתמש ב-INTERSECT.


-- J2  [בינוני]  מזהי המוצרים שהוזמנו גם כ"חדש" וגם כ"מחודש", עם INTERSECT.


-- J3  [בינוני]  מזהי המוצרים שמעולם לא הוזמנו, הפעם עם EXCEPT.


-- J4  [בינוני]  לכל ספק, כולל ספק בלי הזמנות: שם הספק ומספר ההזמנות. הפעם התחל את ה-FROM מטבלת ההזמנות והשתמש ב-RIGHT JOIN.


-- J5  [מתקדם]  השווה בין מזהי המוצרים שהוזמנו כ"חדש" למזהי המוצרים שהוזמנו כ"מחודש": הצג שתי עמודות, new_id ו-refurb_id, כך שמוצר שמופיע רק בצד אחד יקבל NULL בצד השני. השתמש ב-FULL OUTER JOIN בין שתי תת-שאילתות.


-- J6  [בסיסי]  מספר ההזמנה ושם הספק לכל הזמנה, אבל הפעם עם USING במקום ON.


-- J7  [בינוני]  מספר ההזמנה ושם הספק לכל הזמנה, עם NATURAL JOIN.


-- J8  [מתקדם]  מספרי ההזמנות וסכומן של הזמנות שסכומן גבוה מכל ההזמנות של ספק 2. המנוע כאן לא תומך ב-ALL, אז כתוב את הצורה השקולה עם תת-שאילתה סקלרית.


-- J9  [מתקדם]  מספרי ההזמנות וסכומן של הזמנות שסכומן גבוה מלפחות אחת מההזמנות של ספק 3. שוב, הצורה השקולה במקום SOME.


-- ============================================================
-- תת-שאילתות, CTE, EXISTS ופונקציות חלון   (מעבר לסילבוס)
-- ============================================================

-- I1  [בינוני]  ממוצע מספר ההזמנות לספק: ספור הזמנות לכל ספק בתת-שאילתה בתוך FROM, ואז חשב AVG על התוצאה. עמודה אחת.


-- I2  [מתקדם]  עם WITH: מזהי הספקים שמספר ההזמנות שלהם גבוה מהממוצע לספק, עם מספר ההזמנות.


-- I3  [בינוני]  הזמנות שסכומן גבוה מהממוצע הכללי של כל ההזמנות: מספר הזמנה וסכום.


-- I4  [מתקדם]  לכל ספק, ההזמנה (או ההזמנות) עם הסכום הגבוה ביותר שלו: מספר הזמנה, מזהה ספק, סכום. השתמש בתת-שאילתה מתואמת (correlated).


-- I5  [מתקדם]  שמות הספקים שיש להם לפחות החזרה אחת פתוחה ("ממתין לחבילה"). השתמש ב-EXISTS.


-- I6  [בינוני]  שמות המוצרים שמעולם לא הוזמנו, הפעם עם NOT EXISTS.


-- I7  [מתקדם]  לכל ספק, ההזמנה האחרונה שלו לפי תאריך: מזהה ספק, מספר הזמנה, תאריך. השתמש ב-ROW_NUMBER.


-- I8  [מתקדם]  סכום מצטבר של ההזמנות שסופקו לפי תאריך: תאריך, סכום, סכום מצטבר. ממוין לפי תאריך.


-- I9  [מתקדם]  סכום ההזמנות שסופקו בכל חודש (YYYY-MM), והשינוי מהחודש הקודם עם LAG: חודש, סכום, שינוי. ממוין לפי חודש. בחודש הראשון השינוי ריק.


-- I10  [מתקדם]  דרג את המוצרים לפי מספר ההזמנות שלהם מהגבוה לנמוך עם DENSE_RANK: מזהה מוצר, מספר הזמנות, דירוג. ממוין לפי דירוג ואז מזהה מוצר.


-- I11  [מתקדם]  חלקו של כל ספק מסך ההזמנות שסופקו, באחוזים מעוגלים לשתי ספרות אחרי הנקודה: מזהה ספק, סכום, אחוז.


-- I12  [בינוני]  בקרת איכות: צירופים של ספק, מוצר ומצב ציוד שהוזמנו יותר מפעם אחת: מזהה ספק, מזהה מוצר, מצב, מספר הפעמים.


-- I13  [בינוני]  חלק את ההזמנות שסופקו לשלוש קבוצות מחיר: "נמוך" עד 2000 כולל, "בינוני" עד 7000 כולל, "גבוה" מעל. ספור כמה הזמנות בכל קבוצה: קבוצה וכמות.


-- I14  [בינוני]  לכל החזרה סגורה ("סופית"): מספר ההזמנה ומספר הימים שעברו מתאריך ההזמנה עד תאריך ההחזרה. ב-SQLite: julianday(b) - julianday(a). ב-MySQL זה DATEDIFF(b, a).

